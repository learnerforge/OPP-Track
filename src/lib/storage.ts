function readSeedVersion(storage: {
  get: (key: string) => string | null;
}): number {
  try {
    const raw = storage.get(SEED_VERSION_KEY);
    const parsed = raw === null ? 0 : parseInt(raw, 10);
    return Number.isFinite(parsed) ? parsed : 0;
  } catch {
    return 0;
  }
}

function writeSeedVersion(storage: {
  set: (key: string, value: string) => void;
}): void {
  try {
    storage.set(SEED_VERSION_KEY, String(SEED_VERSION));
  } catch {
    /* ignore version-write errors */
  }
}

export function loadOpportunities(): StorageResult {
  const storage = getStorage();

  if (!storage) {
    return { data: [], isNew: true };
  }

  try {
    const raw = storage.get(STORAGE_KEY);
    if (raw === null || raw === undefined) {
      storage.set(STORAGE_KEY, JSON.stringify(SEED_DATA));
      writeSeedVersion(storage);
      return { data: SEED_DATA, isNew: true };
    }
    const parsed = JSON.parse(raw) as Opportunity[];
    if (!Array.isArray(parsed)) {
      throw new Error('Stored data is not an array');
    }

    const storedVersion = readSeedVersion(storage);
    if (storedVersion < SEED_VERSION) {
      const currentSeedIds = new Set(SEED_DATA.map(seed => seed.id));
      const existingIds = new Set(parsed.map(o => o.id));
      const seedById = new Map(SEED_DATA.map(seed => [seed.id, seed]));
      let refreshed = false;
      const mergedList: Opportunity[] = [];
      for (const o of parsed) {
        if (o.id.startsWith('seed_') && !currentSeedIds.has(o.id)) {
          refreshed = true;
          continue;
        }
        const seed = seedById.get(o.id);
        if (seed && o.status === 'Not Started') {
          refreshed = true;
          mergedList.push(seed);
          continue;
        }
        mergedList.push(o);
      }
      const additions = SEED_DATA.filter(seed => !existingIds.has(seed.id));
      if (refreshed || additions.length > 0) {
        const merged = [...mergedList, ...additions];
        storage.set(STORAGE_KEY, JSON.stringify(merged));
        writeSeedVersion(storage);
        return { data: merged, isNew: true };
      }
      writeSeedVersion(storage);
    }

    return { data: parsed, isNew: false };
  } catch (e) {
    throw new StorageError(
      `Failed to load opportunities: ${e instanceof Error ? e.message : 'Unknown error'}`,
      'read'
    );
  }
}

export function saveOpportunities(list: Opportunity[]): void {
  const storage = getStorage();

  if (!storage) {
    throw new StorageError('Storage API not available', 'write');
  }

  try {
    storage.set(STORAGE_KEY, JSON.stringify(list));
    writeSeedVersion(storage);
  } catch (e) {
    throw new StorageError(
      `Failed to save opportunities: ${e instanceof Error ? e.message : 'Unknown error'}`,
      'write'
    );
  }
}
